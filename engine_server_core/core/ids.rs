#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct TokenHash(String);

impl TokenHash {
    pub fn from_hex(hex: impl Into<String>) -> Self {
        Self(hex.into())
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }

    pub fn fingerprint(&self) -> &str {
        let len = self.0.len().min(8);
        &self.0[..len]
    }
}
